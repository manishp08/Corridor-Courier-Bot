#!/usr/bin/env python3
"""Generate Gazebo Harmonic SDF worlds + JSON manifests from the shared
world definitions in sim/ccsim/world.py, so Gazebo and the 2D surrogate use
the same layouts.

  python3 src/cc_gazebo/scripts/generate_worlds.py [--seed 1000] [--out src/cc_gazebo/worlds]

Each world gets <name>.sdf and <name>.json (start, goal, object classes and
footprints, actor trajectories, kidnap event). The eval harness and the
oracle detector read the manifest; the stack itself never does.
"""
