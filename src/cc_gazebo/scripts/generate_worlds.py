GLASS_VIS_FLAG = 2   # LiDAR visibility_mask excludes this bit (see cc_description/urdf/gazebo.xacro)
ACTOR_MESH = "https://fuel.gazebosim.org/1.0/Mingfei/models/actor/tip/files/meshes/walk.dae"

