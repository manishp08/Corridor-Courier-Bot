def box_model(name, x, y, z, yaw, sx, sy, sz, rgba, static=True, extra_visual=""):
    return f"""    <model name="{name}">
      <static>{str(static).lower()}</static>
      <pose>{x:.4f} {y:.4f} {z:.4f} 0 0 {yaw:.4f}</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry></collision>
        <visual name="visual">
          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material>{extra_visual}
        </visual>
      </link>
    </model>
"""


def segment_box(name, seg, thickness, height, rgba, extra_visual=""):
    x1, y1, x2, y2 = seg
    length = math.hypot(x2 - x1, y2 - y1)
    return box_model(name, (x1 + x2) / 2, (y1 + y2) / 2, height / 2, math.atan2(y2 - y1, x2 - x1),
                     length + thickness, thickness, height, rgba, extra_visual=extra_visual)


def cart_model(name, o):
    """Cart: thin legs cross the LiDAR plane, the body and handle sit above it."""
    c, s = math.cos(o.yaw), math.sin(o.yaw)
    hx, hy = o.sx / 2 - 0.04, o.sy / 2 - 0.04
    legs = ""
    for k, (a, b) in enumerate([(hx, hy), (-hx, hy), (-hx, -hy), (hx, -hy)]):
        legs += f"""        <collision name="leg{k}"><pose>{a:.3f} {b:.3f} 0.15 0 0 0</pose><geometry><cylinder><radius>0.02</radius><length>0.30</length></cylinder></geometry></collision>
        <visual name="leg{k}_v"><pose>{a:.3f} {b:.3f} 0.15 0 0 0</pose><geometry><cylinder><radius>0.02</radius><length>0.30</length></cylinder></geometry></visual>
"""
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{o.x:.4f} {o.y:.4f} 0 0 0 {o.yaw:.4f}</pose>
      <link name="link">
{legs}        <collision name="body"><pose>0 0 0.5 0 0 0</pose><geometry><box><size>{o.sx:.3f} {o.sy:.3f} 0.4</size></box></geometry></collision>
        <visual name="body_v"><pose>0 0 0.5 0 0 0</pose><geometry><box><size>{o.sx:.3f} {o.sy:.3f} 0.4</size></box></geometry>
          <material><ambient>0.7 0.7 0.75 1</ambient><diffuse>0.7 0.7 0.75 1</diffuse></material></visual>
        <collision name="handle"><pose>{-o.sx / 2:.3f} 0 0.9 0 0 0</pose><geometry><box><size>0.03 {o.sy:.3f} 0.03</size></box></geometry></collision>
        <visual name="handle_v"><pose>{-o.sx / 2:.3f} 0 0.9 0 0 0</pose><geometry><box><size>0.03 {o.sy:.3f} 0.03</size></box></geometry></visual>
      </link>
    </model>
"""


def actor_xml(name, a):
    """Ping-pong walk starting at the actor's phase position, looped."""
    x, y, vx, vy = a.state()
    p_a, p_b = a.waypoints[0], a.waypoints[-1]
    forward = (vx * (p_b[0] - p_a[0]) + vy * (p_b[1] - p_a[1])) >= 0
    far, near = (p_b, p_a) if forward else (p_a, p_b)
    pts = [(x, y), tuple(far), tuple(near), (x, y)]
    t, wps = 0.0, []
    for k, (px, py) in enumerate(pts):
        if k > 0:
            t += math.hypot(px - pts[k - 1][0], py - pts[k - 1][1]) / a.speed
        nxt = pts[min(k + 1, len(pts) - 1)] if k < len(pts) - 1 else pts[1]
        yaw = math.atan2(nxt[1] - py, nxt[0] - px)
        wps.append(f"          <waypoint><time>{t:.3f}</time><pose>{px:.3f} {py:.3f} 1.0 0 0 {yaw:.3f}</pose></waypoint>")
    return f"""    <actor name="{name}">
      <skin><filename>{ACTOR_MESH}</filename><scale>1.0</scale></skin>
      <animation name="walking"><filename>{ACTOR_MESH}</filename><interpolate_x>true</interpolate_x></animation>
      <script>
        <loop>true</loop>
        <auto_start>true</auto_start>
        <trajectory id="0" type="walking">
{chr(10).join(wps)}
        </trajectory>
      </script>
    </actor>
"""


def generate(name, seed, out_dir):
    w = make_world(name, seed)
    parts = [HEADER.format(name=name, seed=seed, gui=gui_block(w.start))]
    for k, seg in enumerate(w.walls):
        parts.append(segment_box(f"wall_{k}", seg, WALL_T, WALL_H, "0.75 0.75 0.72 1"))
    glass_extra = f"\n          <transparency>0.8</transparency>\n          <visibility_flags>{GLASS_VIS_FLAG}</visibility_flags>"
    for k, seg in enumerate(w.glass):
        parts.append(segment_box(f"glass_{k}", seg, 0.02, WALL_H, "0.6 0.8 0.9 0.3", extra_visual=glass_extra))
    objects = []
    for k, o in enumerate(w.obstacles):
        nm = f"{o.kind}_{k}"
        if o.kind == "cart":
            parts.append(cart_model(nm, o))
        else:
            rgba = {"pallet": "0.6 0.45 0.25 1", "low_box": "0.8 0.6 0.3 1", "shelf": "0.4 0.4 0.45 1"}[o.kind]
            parts.append(box_model(nm, o.x, o.y, o.height / 2, o.yaw, o.sx, o.sy, o.height, rgba))
        objects.append({"name": nm, "kind": o.kind, "class": o.cls, "x": o.x, "y": o.y, "yaw": o.yaw,
                        "size_x": o.sx, "size_y": o.sy, "height": o.height})
    actors = []
    for k, a in enumerate(w.actors):
        parts.append(actor_xml(f"person_{k}", a))
        actors.append({"name": f"person_{k}", "waypoints": a.waypoints.tolist(), "speed": a.speed,
                       "phase": a.phase, "radius": a.radius})
    parts.append("  </world>\n</sdf>\n")
    (out_dir / f"{name}.sdf").write_text("".join(parts))
    manifest = {
        "world": name, "seed": seed, "bounds": list(w.bounds),
        "start": [float(v) for v in w.start], "goal": [float(v) for v in w.goal], "timeout": w.timeout,
        "walls": w.walls.tolist(), "glass": w.glass.tolist(), "objects": objects, "actors": actors,
        "kidnap": None if w.kidnap is None else {"time": w.kidnap[0], "pose": [float(v) for v in w.kidnap[1]]},
    }
    (out_dir / f"{name}.json").write_text(json.dumps(manifest, indent=2))


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--seed", type=int, default=1000)
    p.add_argument("--out", default=str(HERE.parents[1] / "worlds"))
    a = p.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for name in WORLD_NAMES:
        generate(name, a.seed, out)
        print("wrote", out / f"{name}.sdf")


if __name__ == "__main__":
    main()
